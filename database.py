"""Small DB-API bridge for this shop's existing SQLite queries.

DATABASE_URL switches ALL bot and Mini App queries to PostgreSQL.
There is deliberately no fallback to a local DB when cloud access fails.
"""
import os
import re
import sqlite3


class Row:
    def __init__(self, names, values):
        self._names = names
        self._values = tuple(values)

    def __getitem__(self, key):
        return self._values[self._names.index(key)] if isinstance(key, str) else self._values[key]

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def keys(self):
        return self._names


def postgres_sql(sql):
    """Translate only the SQLite constructs used in this application's queries."""
    sql = sql.strip().rstrip(";")
    sql = re.sub(r"\bINTEGER PRIMARY KEY AUTOINCREMENT\b",
                 "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql, flags=re.I)
    # Telegram IDs are larger than PostgreSQL's 32-bit INTEGER range.
    sql = re.sub(r"\bINTEGER\b", "BIGINT", sql, flags=re.I)
    sql = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sql, flags=re.I)
    ignore = bool(re.match(r"INSERT\s+OR\s+IGNORE\b", sql, flags=re.I))
    sql = re.sub(r"INSERT\s+OR\s+IGNORE\b", "INSERT", sql, flags=re.I)
    sql = sql.replace("user_id GLOB '[0-9]*'", "user_id ~ '^[0-9]+$'")
    sql = re.sub(r"order_id\s*=\s*\?\s+COLLATE\s+NOCASE",
                 "LOWER(order_id) = LOWER(?)", sql, flags=re.I)
    # Convert bind markers, but leave question marks inside quoted strings alone.
    parts = re.split(r"('(?:[^']|'')*'|\"(?:[^\"]|\"\")*\")", sql)
    sql = "".join(p if i % 2 else p.replace("?", "%s") for i, p in enumerate(parts))
    if ignore:
        sql += " ON CONFLICT DO NOTHING"
    return sql


class Cursor:
    def __init__(self, connection):
        self.connection = connection
        self.raw = None
        self.lastrowid = None

    def execute(self, sql, params=()):
        self.lastrowid = None
        if self.raw is not None:
            self.raw.close()
        self.raw = self.connection.raw.cursor()
        pragma = re.fullmatch(r"\s*PRAGMA table_info\((\w+)\)\s*;?\s*", sql, re.I)
        if pragma:
            self.raw.execute(
                "SELECT ordinal_position - 1 AS cid, column_name AS name, "
                "data_type AS type, 0 AS notnull, column_default AS dflt_value, 0 AS pk "
                "FROM information_schema.columns WHERE table_schema = 'public' "
                "AND table_name = %s ORDER BY ordinal_position",
                (pragma.group(1),),
            )
            return self
        sql = postgres_sql(sql)
        insert = re.match(r"INSERT\s+INTO\s+(\w+)\b", sql, re.I)
        returns_id = insert and insert.group(1).lower() in {
            "orders", "products", "leads", "broadcasts", "broadcast_log"
        } and "RETURNING" not in sql.upper()
        if returns_id:
            sql += " RETURNING id"
        self.raw.execute(sql, params or None)
        created = re.match(r"CREATE TABLE IF NOT EXISTS (\w+)\b", sql, re.I)
        if created:
            # Keep shop tables protected; queries run only as the trusted
            # backend role that owns these tables, never as a public client.
            self.connection.raw.execute(
                f'ALTER TABLE "{created.group(1)}" ENABLE ROW LEVEL SECURITY'
            )
        if returns_id:
            result = self.raw.fetchone()
            self.lastrowid = result[0] if result else None
        return self

    @property
    def rowcount(self):
        return self.raw.rowcount

    def _row(self, value):
        if value is None:
            return None
        return Row([c.name for c in self.raw.description], value)

    def fetchone(self):
        return self._row(self.raw.fetchone())

    def fetchall(self):
        return [self._row(row) for row in self.raw.fetchall()]

    def __iter__(self):
        while (row := self.fetchone()) is not None:
            yield row


class Connection:
    def __init__(self, url):
        import psycopg
        # Disable prepared statements to also support transaction poolers.
        self.raw = psycopg.connect(url, connect_timeout=15,
                                  sslmode="require", client_encoding="utf8",
                                  prepare_threshold=None)

    def cursor(self):
        return Cursor(self)

    def execute(self, sql, params=()):
        return self.cursor().execute(sql, params)

    def executescript(self, sql):
        for statement in sql.split(";"):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def connect(local_path):
    url = os.getenv("DATABASE_URL", "").strip()
    if url:
        return Connection(url)
    conn = sqlite3.connect(local_path)
    conn.row_factory = sqlite3.Row
    return conn


def validate_config():
    keys = ("DATABASE_URL", "AWS_ENDPOINT_URL_S3", "AWS_ACCESS_KEY_ID",
            "AWS_SECRET_ACCESS_KEY", "AWS_REGION")
    present = [bool(os.getenv(key, "").strip()) for key in keys]
    if any(present) and not all(present):
        missing = ", ".join(key for key, exists in zip(keys, present) if not exists)
        raise RuntimeError("Не настроено постоянное хранилище Neon. Добавьте в Render: " + missing)
    if os.getenv("RENDER_EXTERNAL_URL") and not all(present):
        raise RuntimeError(
            "Запуск остановлен: на Render не настроено постоянное хранилище. "
            "Задайте DATABASE_URL и AWS_* из Neon Connect → Storage. "
            "Локальная база на бесплатном Render теряется при перезапуске."
        )
